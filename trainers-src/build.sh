#!/usr/bin/env bash
# Builds every kit-based trainer in _src/ into a standalone page of the site:
#   _src/<name>.src.html  +  _kit/trainer-kit.css  +  _kit/trainer-kit.js   →   ../<section>/<page>.html
# The shared kit is inlined, so each generated .html works on its own (no shared files at runtime).
# Run from Git Bash or WSL:   ./trainers-src/build.sh
set -euo pipefail
cd "$(dirname "$0")"

# source name -> page in the site
declare -A OUT=(
  [cv-queue-trainer]=../cpp/condition-variable.html
  [dp-trainer]=../dsa/dp.html
  [linked-list-trainer]=../dsa/linked-list.html
  [sta-trainer]=../eda/static-timing.html
)

for src in _src/*.src.html; do
  name=$(basename "$src" .src.html)
  out=${OUT[$name]:-}
  if [ -z "$out" ]; then echo "skip $src (no entry in OUT)"; continue; fi
  awk -v css="_kit/trainer-kit.css" -v js="_kit/trainer-kit.js" -v src="trainers-src/$src" '
    NR == 1 { print; print "<!-- GENERATED by trainers-src/build.sh from " src " and _kit/. Edit those files, then run the build. -->"; next }
    /<!-- @kit:css -->/ { print "<style>"; while ((getline line < css) > 0) print line; close(css); print "</style>"; next }
    /<!-- @kit:js -->/  { print "<script>"; while ((getline line < js) > 0) print line; close(js); print "</script>"; next }
    { print }
  ' "$src" > "$out"
  echo "built ${out#../}"
done
